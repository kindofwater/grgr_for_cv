-- 날짜: 2026-07-27 · 담당: 배경록
--
-- 학교별 경품 구성이 다르므로 university_id를 분리한다.
-- 제목과 학교 범위 기준 멱등 처리하여 reset·재push 시 중복을 막는다.

insert into public.notices (title, content, is_pinned, university_id)
select
  '[이벤트] 근무지 리뷰 작성 이벤트',
  $notice$안녕하세요, 근로고래입니다. 🐳

근로고래 오픈을 기념하여 근무지 리뷰 작성 이벤트를 진행합니다.

근로장학생 지원 전, 실제 근무자들의 업무 내용과 분위기, 근무 강도 등의 정보가 있으면 훨씬 도움이 되지 않을까 하는 마음으로 근로고래를 만들었습니다.

이전에 근로장학생으로 일해보신 분들의 짧은 리뷰 하나가 다음 지원자에게 큰 도움이 됩니다. 여러분의 근무 경험을 공유해주세요!


■ 이벤트 안내

· 기간: 7월 27일 ~ 8월 15일
· 대상: 기간 내 근무지 리뷰를 작성해주신 분
· 경품: 메가커피 1만원권 1명, 메가커피 아메리카노 교환권 10명
· 당첨자 안내: 가입 이메일을 통해 개별 안내


■ 참여 방법

1. 근로고래에서 근무지를 검색합니다.
2. 본인이 근무한 곳의 리뷰를 작성합니다.
3. 이벤트 기간 내 작성한 리뷰를 대상으로 추첨이 진행됩니다.


여러분이 남겨주시는 리뷰로 더 많은 학생이 자신에게 맞는 근무지를 찾을 수 있습니다.

근로고래와 함께 더 좋은 근로장학생 경험을 만들어가요.
