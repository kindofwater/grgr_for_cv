■ 한눈에 보는 차이

· 운영 주체
  국가근로 — 한국장학재단(KOSAF)
  교내근로 — 각 대학 (고려대학교 자체)

· 지원 자격
  국가근로 — 소득분위·성적 기준이 있음
  교내근로 — 학교·부서 기준

· 시급
  국가근로 — 재단이 정한 단가 (아래 참고)
  교내근로 — 학교마다 다름

· 모집 시기
  국가근로 — 학기 단위 정기 모집
  교내근로 — 부서별 수시·비정기

근로고래에서는 이 둘을 '국가근장'과 '학교근장' 태그로 구분해 두었습니다.


