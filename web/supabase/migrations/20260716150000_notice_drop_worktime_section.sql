눈여겨볼 점이 하나 있습니다. 장애대학생 봉사유형은 교내 근무지에서
일해도 교외 시급(12,790원)이 적용됩니다. 교내에서 근무하면서 교외
시급을 받을 수 있는 몇 안 되는 경우입니다.


■ 국가근로, 나는 해당될까

한국장학재단 기본 요건
  · 학자금 지원구간 9구간 이하
  · 직전학기 성적 100점 만점에 70점 이상 (약 1.88 / 4.5 수준)
  · 학부 재학생
    (휴학생·졸업유예자·수료자·초과학기자 등은 대체로 제외)

고려대학교 적용 기준
  · 소득분위 0~8분위 이내

⚠️ 소득분위 커트라인은 학교마다 다릅니다.
재단 기본 요건은 9구간 이하지만, 고려대학교는 0~8분위로 안내하고 있고
6분위까지만 선발하는 학교도 있습니다. 대학이 배정받은 예산과 지원자 수에
따라 학기마다 달라질 수 있으니, 최종 확인은 반드시 소속 학교 공지로 하세요.


