// ── 단과대학 ↔ 학과 매핑 (대학별 이중 배열) ──
// 1차 index = 대학(UNIV_EMAIL_KEYS와 병렬: 0=고려대, 1=서울대).
// 2차 index 병렬: departments[u][i] = colleges[u][i]의 학과 목록.
// 단독 학부(디자인조형학부·자유전공학부·첨단융합학부 등)는 자신이 유일한 단과대이자 학과 — 1:1 취급.

// 대학 키 = 이메일 도메인의 첫 라벨(@ 바로 뒤). colleges/departments의 1차 index와 병렬.
export const UNIV_EMAIL_KEYS = ['korea', 'snu']

// 도메인(@ 뒤 전체) → 대학 index. 첫 라벨로 판정, 미매칭·비정상은 0(고려대) — 단일 대학 시절과 같은 기본값.
export function univIndexFromDomain(domain) {
  const first = (domain ?? '').toLowerCase().split('.')[0]
  const i = UNIV_EMAIL_KEYS.indexOf(first)
  return i < 0 ? 0 : i
}

// 이메일 → 대학 index. 미매칭(기타 .ac.kr·비정상 입력)은 0(고려대).
export function univIndexFromEmail(email) {
  return univIndexFromDomain((email ?? '').split('@')[1])
}

// 미등록 도메인일 때 학교 드롭다운이 폴백하는 도메인 — univIndexFromEmail 기본 0(고려대)과 같은 정책.
export const FALLBACK_EMAIL_DOMAIN = 'korea.ac.kr'

// 이메일 도메인과 일치하는 universities 행만 필터 — 회원가입 학교 드롭다운용.
// 이 드롭다운은 "학교 선택"이 아니라 같은 도메인의 분리 캠퍼스(서울/세종) 선택 용도다:
// 학교 자체는 이메일이 결정하므로, 도메인 불일치 학교는 선택지에 넣지 않는다
// (등록된 학교끼리의 이메일↔소속 불일치 원천 차단).
// 미등록 도메인·비정상 입력은 고려대(FALLBACK_EMAIL_DOMAIN) 캠퍼스들로 폴백 —
// 기존(기본값 고려대) 동작 유지 결정(2026-07-17). 그래도 비면 빈 배열(고려대 행 자체가 없는 이상 상황).
export function universitiesForEmail(universities, email) {
  const list = universities ?? []
  const domain = ((email ?? '').split('@')[1] ?? '').trim().toLowerCase()
  const byDomain = (d) => list.filter((u) => (u.email_domain ?? '').trim().toLowerCase() === d)
  const matched = domain ? byDomain(domain) : []
  return matched.length ? matched : byDomain(FALLBACK_EMAIL_DOMAIN)
}

